"""Export the deterministic demo store for the Netlify JavaScript adapter.

Netlify Functions currently document JavaScript/TypeScript and Go runtimes, not
Python. The FastAPI application remains the real backend (local/Docker), while
the Netlify deployment uses a self-contained JavaScript adapter seeded from the
same data. This script runs during the Netlify build.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from app.seed import build_seed  # noqa: E402

TARGET = ROOT / "netlify" / "functions" / "api" / "seed.json"
TARGET_MJS = ROOT / "netlify" / "functions" / "api" / "seed.mjs"


def main() -> None:
    data = build_seed()
    payload = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(payload, encoding="utf-8")
    TARGET_MJS.write_text(
        "// Generated by scripts/export_seed.py. Do not edit by hand.\n"
        f"export default {payload};\n",
        encoding="utf-8",
    )
    print(f"exported demo seed -> {TARGET.relative_to(ROOT)} ({TARGET.stat().st_size} bytes)")
    print(f"exported demo module -> {TARGET_MJS.relative_to(ROOT)} ({TARGET_MJS.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
